def _frame_entry(entry, kind, index, fields):
    """One frame.json entry as a dict holding ``fields``, or SystemExit naming what is missing."""
    if not isinstance(entry, dict):
        raise SystemExit(f"frame.json: {kind} {index} must be an object, got {entry!r}.")
    missing = [field for field in fields if field not in entry]
    if missing:
        label = f"{kind} '{entry['key']}'" if "key" in entry else f"{kind} {index}"
        raise SystemExit(f"frame.json: {label} lacks {missing}.")
    return entry


def _minimize_flag(entry):
    """The objective's explicit minimize flag (0/1 or false/true).

    Required, like in the Unity init message: a silent default of 0 turned a minimized
    objective that someone forgot to flag into a maximized one, i.e. an exactly inverted
    source whose frame stamp then matched any study that made the same omission.
    """
    flag = entry["minimize"]
    if isinstance(flag, bool):
        return int(flag)
    if isinstance(flag, (int, float)) and flag in (0, 1):
        return int(flag)
    raise SystemExit(
        f"frame.json: objective '{entry['key']}' needs \"minimize\": 0 or 1, got {flag!r}."
    )


def load_frame(frame_path):
    with open(frame_path, "r", encoding="utf-8") as f:
        payload = json.load(f)
    if not isinstance(payload, dict):
        raise SystemExit("frame.json must be an object with 'parameters' and 'objectives'.")
    params = payload.get("parameters") or []
    objs = payload.get("objectives") or []
    if not params or not objs:
        raise SystemExit("frame.json must define non-empty 'parameters' and 'objectives'.")
    params = [_frame_entry(p, "parameter", i, ("key", "low", "high")) for i, p in enumerate(params)]
    objs = [_frame_entry(o, "objective", i, ("key", "low", "high", "minimize")) for i, o in enumerate(objs)]
    parameter_names = [str(p["key"]) for p in params]
    parameters_info = [(float(p["low"]), float(p["high"])) for p in params]
    objective_names = [str(o["key"]) for o in objs]
    objectives_info = [(float(o["low"]), float(o["high"]), _minimize_flag(o)) for o in objs]
    if len(objective_names) < 2:
        raise SystemExit("Meta-TAF sources are multi-objective: define at least 2 objectives.")
    for name, bounds in zip(parameter_names + objective_names, parameters_info + objectives_info):
        lo, hi = bounds[0], bounds[1]
        if not (math.isfinite(lo) and math.isfinite(hi)) or hi < lo:
            raise SystemExit(f"frame.json: '{name}' needs finite bounds with low <= high, got [{lo}, {hi}].")
    frame = meta_fingerprint.canonical_frame(
        parameter_names, parameters_info, objective_names, objectives_info
    )
    return frame, parameter_names, parameters_info, objective_names, objectives_info


def sanitize_name(name):
    cleaned = re.sub(r"[^A-Za-z0-9_.-]+", "_", str(name)).strip("_.")
    return cleaned or "source"


LOG_FILENAME = "ObservationsPerEvaluation.csv"


def run_identity(run_path):
    """The run a path refers to: the run folder for '<run>/ObservationsPerEvaluation.csv',
    otherwise the absolute path itself (a run folder, or a CSV under another name)."""
    path = os.path.normpath(os.path.abspath(str(run_path)))
    if os.path.basename(path).lower() == LOG_FILENAME.lower():
        path = os.path.dirname(path)
    return path


def _same_file(path_a, path_b):
    """Whether two existing paths are one file or folder; None when that cannot be told
    (a path is missing, or the file system reports inode 0 for everything, as some network
    file systems do -- os.path.samefile would then call every pair the same)."""
    try:
        stat_a, stat_b = os.stat(path_a), os.stat(path_b)
    except (OSError, ValueError):
        return None
    if not (stat_a.st_ino and stat_b.st_ino):
        return None
    return os.path.samestat(stat_a, stat_b)


def same_run(path_a, path_b):
    """True when two paths (run folder or its CSV, any spelling) name the same run.

    Paths that exist are compared by file identity, which also catches another spelling on a
    case-insensitive file system (normcase folds case on Windows only, not on macOS);
    otherwise, e.g. for a run_path recorded on another machine, by the normalized path.
    """
    a, b = run_identity(path_a), run_identity(path_b)
    same = _same_file(a, b)
    if same is not None:
        return same

    def key(path):
        return os.path.normcase(os.path.realpath(path))
    return key(a) == key(b)


def path_hash(run_path):
    """Short, stable hash of a run's absolute path (disambiguates colliding names)."""
    key = os.path.normcase(os.path.realpath(run_identity(run_path)))
    return hashlib.sha256(key.encode("utf-8")).hexdigest()[:8]


def derive_name(run_path):
    """Artifact name from the run's path tail: '<participant>_<condition>_<run>'.

    Depends on the path only. The former '<index>_' prefix tied the name to the run's
    position on the command line, so rebuilding a population into the same --out with one
    more (or reordered) run published renamed duplicates next to the existing artifacts and
    the duplicated participants counted twice in every later run. A CSV path is named after
    its run folder ('<run>/ObservationsPerEvaluation.csv'), or after its own file name when
    the CSV is named otherwise, so the participant folder stays in the name.
    """
    path = run_identity(run_path)
    parts = [p for p in path.split(os.sep) if p and not p.endswith(":")]
    if parts and os.path.splitext(parts[-1])[1].lower() == ".csv":
        parts[-1] = os.path.splitext(parts[-1])[0]
    return sanitize_name("_".join(parts[-3:]))


def existing_artifacts(out_dir):
    """{name: provenance} of the artifacts already in ``out_dir`` (provenance {} if unreadable)."""
    gp_dir = os.path.join(out_dir, "gp_states")
    if not os.path.isdir(gp_dir):
        return {}
    found = {}
    for fname in sorted(os.listdir(gp_dir)):
        if not fname.endswith(".json") or fname.startswith("."):
            continue  # also macOS AppleDouble '._<name>.json' files
        provenance = {}
        try:
            with open(os.path.join(gp_dir, fname), "r", encoding="utf-8") as f:
                payload = json.load(f)
            if isinstance(payload, dict) and isinstance(payload.get("provenance"), dict):
                provenance = payload["provenance"]
        except (OSError, ValueError):
            pass
        found[fname[:-len(".json")]] = provenance
    return found


def stored_observations(out_dir, names):
    """{name: (x_values, y_values)} of the artifacts in ``out_dir`` whose trajectory reads."""
    found = {}
    for name in names:
        try:
            with open(os.path.join(out_dir, "trajectories", f"{name}.json"), "r", encoding="utf-8") as f:
                payload = json.load(f)
            found[name] = (np.asarray(payload["x_values"], dtype=np.float64),
                           np.asarray(payload["y_values"], dtype=np.float64))
        except (OSError, ValueError, KeyError, TypeError):
            continue
    return found


def names_holding_run(run, existing, observations=None, stored=None):
    """Names in ``out_dir`` whose artifact was built from ``run``.

    By the provenance run_path, or -- for a name derived from the same path tail (plain,
    hashed, or an older version's '<index>_<tail>') -- by identical normalized observations
    (``observations``: {run: (x_unit, y_norm)}, ``stored``: stored_observations): a
    population built on another machine, or before the project folder moved, records another
    absolute path for the same run, which would otherwise be built a second time under a
    hashed name.
    """
    held = {
        name for name, provenance in existing.items()
        if isinstance(provenance.get("run_path"), str) and same_run(provenance["run_path"], run)
    }
    mine = (observations or {}).get(run)
    if mine is not None:
        tail = re.escape(derive_name(run))
        held.update(
            name for name, theirs in (stored or {}).items()
            if re.fullmatch(rf"(\d+_)?{tail}(-[0-9a-f]{{8}})?", name)
            and all(np.shape(a) == np.shape(b) and np.array_equal(a, b) for a, b in zip(mine, theirs))
        )
    return sorted(held)


def assign_names(runs, explicit_names, existing, observations=None, stored=None):
    """One artifact name per run: explicit, else the path tail plus a path hash on collision.

    A derived name collides when another run of this call derives the same tail, or when
    ``out_dir`` already holds that name for a different run. A run already in ``out_dir``
    keeps the name it has there -- its plain or hashed name, or the index-prefixed name
    ('00_p01_main_run') an older meta_train.py gave it, also when it was built from another
    path (names_holding_run) -- so the names of a population do not depend on which runs are
    rebuilt together, and rebuilding a folder built by an older version, on another machine
    or before the project moved, with one more run adds that run only instead of a second
    copy of every other.
    """
    if explicit_names is not None:
        return [sanitize_name(n) for n in explicit_names]
    tails = [derive_name(run) for run in runs]
    names = []
    for run, tail in zip(runs, tails):
        hashed = f"{tail}-{path_hash(run)}"
        held = names_holding_run(run, existing, observations, stored)
        if held:
            names.append(tail if tail in held else hashed if hashed in held else held[0])
        elif tail in existing:
            names.append(hashed)  # the plain name belongs to another run
        elif hashed in existing:
            names.append(hashed)  # built earlier next to a run with the same tail
        else:
            clash = any(t == tail and not same_run(other, run) for other, t in zip(runs, tails))
            names.append(hashed if clash else tail)
    return names


def same_run_other_names(run, name, existing, out_dir=None, observations=None, stored=None):
    """Names in ``out_dir`` that hold this same run under a name other than ``name``.

    A name whose gp_state is the very file of ``name`` (another spelling of it on a
    case-insensitive file system) is the same artifact, not a second copy.
    """
    others = [other for other in names_holding_run(run, existing, observations, stored)
              if other != name]
    if out_dir is None:
        return others
    mine = os.path.join(out_dir, "gp_states", f"{name}.json")
    return [other for other in others
            if not _same_file(mine, os.path.join(out_dir, "gp_states", f"{other}.json"))]


