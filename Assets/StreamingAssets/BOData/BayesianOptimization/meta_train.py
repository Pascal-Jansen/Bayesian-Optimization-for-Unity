# meta_train.py — build Meta-TAF population models from completed BOforUnity runs.
#
# Offline tool (run by the researcher, never by participants). It converts each finished
# run's ObservationsPerEvaluation.csv into one "source artifact" pair understood by the
# Meta-TAF backend / openbo:
#
#     <out>/trajectories/<name>.json   x_values (n,d) in [0,1]^d, y_values (n,M) in
#                                      [-1,1] maximization, pareto_front (P,M)
#     <out>/gp_states/<name>.json      per-objective GP hyperparameters + the study
#                                      frame + provenance
#
# Everything is normalized through bo_normalize (the exact transform the live backends
# apply), and the study frame is stamped into every artifact so the runtime can refuse
# sources whose bounds or minimize flags do not match the live study -- a mismatch there
# would silently transfer a rescaled or inverted response surface.
#
# Usage:
#   python meta_train.py --frame frame.json --out ../MetaSources/MyStudy \
#       --source-type human --y-calibration measured runDir1 runDir2 ...
#
# --source-type and --y-calibration are REQUIRED provenance stamps (who produced the
# objective values, and whether they were measured from real participants/systems or
# generated by a model such as LLM personas). They are written into every artifact and
# copied into each live run's MetaSourcesUsed audit trail -- label them honestly.
#
# Each artifact is named after its run's path tail (<participant>_<condition>_<run>), never
# after its position on the command line, and a run already in --out keeps the name it has
# there (also an index-prefixed one from an older version), so rebuilding into the same --out
# finds the same names; existing artifacts are only replaced with --force. After every build the folder's
# population manifest (population.json: names, hashes, frame digest) is rewritten; the
# runtime refuses to start when the population it loads differs from it. --dry-run checks
# names and runs without fitting or writing; --manifest-only rewrites just the manifest.
#
# frame.json mirrors the Unity configuration (every objective needs its "minimize" flag):
#   {
#     "parameters": [{"key": "speed", "low": 0.0, "high": 10.0}, ...],
#     "objectives": [{"key": "comfort", "low": 0.0, "high": 100.0, "minimize": 0}, ...]
#   }
#
# Requires the full stack (openbo + botorch); see docs/meta-taf-student-guide.md.

